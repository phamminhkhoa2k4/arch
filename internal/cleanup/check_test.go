package cleanup

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

// writeTestPlan generates a plan directory for the given component and
// runtime and returns it.
func writeTestPlan(t *testing.T, c Component, rt Runtime) string {
	t.Helper()
	dir, _, err := WritePlan(t.TempDir(), Build(c, rt), Meta{
		VerdictState: "ORPHANED", Coverage: "HIGH", WindowLine: "w",
		GeneratedAt: time.Now(),
	})
	if err != nil {
		t.Fatalf("write plan: %v", err)
	}
	return dir
}

// An untouched plan directory passes every check.
func TestCheckPassesUnmodifiedPlan(t *testing.T) {
	dir := writeTestPlan(t, systemdComp(), testRuntime())
	res, err := Check(dir)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if !res.OK() {
		t.Errorf("problems = %v, want none", res.Problems)
	}
	if len(res.Manifest.Scripts) != 6 {
		t.Errorf("manifest scripts = %d, want 6", len(res.Manifest.Scripts))
	}
	if res.Manifest.ScanID != 7 || res.Manifest.RulesHash != "ruleshash" {
		t.Errorf("manifest provenance lost: %+v", res.Manifest)
	}
}

// Editing a stage script after generation must be detected.
func TestCheckDetectsModifiedScript(t *testing.T) {
	dir := writeTestPlan(t, systemdComp(), testRuntime())
	path := filepath.Join(dir, "05-removed.sh")
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read script: %v", err)
	}
	if err := os.WriteFile(path, append(body, []byte("\n# tampered\n")...), 0o755); err != nil {
		t.Fatalf("write script: %v", err)
	}

	res, err := Check(dir)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if res.OK() {
		t.Fatal("check must fail after a script is modified")
	}
	if !strings.Contains(strings.Join(res.Problems, "\n"), "05-removed.sh was modified") {
		t.Errorf("problems = %v, want a modification diagnostic", res.Problems)
	}
}

// A deleted stage script must be detected.
func TestCheckDetectsMissingScript(t *testing.T) {
	dir := writeTestPlan(t, systemdComp(), testRuntime())
	if err := os.Remove(filepath.Join(dir, "01-candidate.sh")); err != nil {
		t.Fatalf("remove script: %v", err)
	}

	res, err := Check(dir)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if res.OK() {
		t.Fatal("check must fail after a script is removed")
	}
	if !strings.Contains(strings.Join(res.Problems, "\n"), "01-candidate.sh is missing") {
		t.Errorf("problems = %v, want a missing-file diagnostic", res.Problems)
	}
}

// A plan directory with no manifest cannot be trusted.
func TestCheckReportsMissingManifest(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "01-candidate.sh"), []byte("#!/bin/sh\n"), 0o755); err != nil {
		t.Fatalf("write script: %v", err)
	}

	res, err := Check(dir)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if res.OK() {
		t.Fatal("check must fail without a manifest")
	}
	if !strings.Contains(strings.Join(res.Problems, "\n"), ManifestFile) {
		t.Errorf("problems = %v, want a manifest diagnostic", res.Problems)
	}
}

// An unreadable manifest is a problem, not a crash.
func TestCheckReportsCorruptManifest(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, ManifestFile), []byte("{not json"), 0o644); err != nil {
		t.Fatalf("write manifest: %v", err)
	}

	res, err := Check(dir)
	if err != nil {
		t.Fatalf("check must not return an error for a corrupt manifest: %v", err)
	}
	if res.OK() {
		t.Fatal("check must fail on a corrupt manifest")
	}
}

// A manifest written by an unsupported version is rejected.
func TestCheckRejectsUnknownManifestVersion(t *testing.T) {
	dir := writeTestPlan(t, systemdComp(), testRuntime())
	path := filepath.Join(dir, ManifestFile)
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read manifest: %v", err)
	}
	if err := os.WriteFile(path,
		[]byte(strings.Replace(string(body), `"manifest_version": 1`, `"manifest_version": 99`, 1)),
		0o644); err != nil {
		t.Fatalf("write manifest: %v", err)
	}

	res, err := Check(dir)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if res.OK() {
		t.Fatal("check must reject an unsupported manifest version")
	}
	if !strings.Contains(strings.Join(res.Problems, "\n"), "not supported") {
		t.Errorf("problems = %v, want a version diagnostic", res.Problems)
	}
}

// Partial provenance is reported as a warning rather than a hard
// failure, so a plan generated by an older tool still runs.
func TestCheckWarnsOnMissingProvenance(t *testing.T) {
	rt := testRuntime()
	rt.ScanID = 0
	rt.RulesHash = ""
	dir := writeTestPlan(t, Component{
		Kind: "container", Name: "x", IdentityKey: "container|x", Ref: "x",
	}, rt)

	res, err := Check(dir)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if !res.OK() {
		t.Errorf("missing provenance should warn, not fail: %v", res.Problems)
	}
	if len(res.Warnings) < 2 {
		t.Errorf("warnings = %v, want at least the scan id and rules hash warnings", res.Warnings)
	}
}
